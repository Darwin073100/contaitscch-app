-- CONTAITSCCH: esquema base (sin Supabase Auth). Modelo: docs/database/postgres.dbml
-- Las tablas solo se acceden por funciones RPC (security definer). RLS activo y sin políticas.

create extension if not exists pgcrypto with schema extensions;

-- ===================== Permisos por defecto =====================
-- Supabase da a anon/authenticated permisos sobre todo lo nuevo en public. Aquí se quitan:
-- cada función RPC concede su EXECUTE de forma explícita.
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;
alter default privileges for role postgres in schema public revoke execute on functions from public, anon, authenticated;

-- ===================== updated_at automático =====================
create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- ===================== Tablas =====================
create table public.profile (
  id                  uuid        primary key default gen_random_uuid(),
  email               text        not null unique
                                  check (email = lower(btrim(email)) and char_length(email) >= 3 and position('@' in email) > 1),
  password_hash       text        not null check (password_hash ~ '^[0-9a-f]{64}$'),
  password_salt       text        not null check (password_salt ~ '^[0-9a-f]{32}$'),
  password_iterations integer     not null default 60000 check (password_iterations between 10000 and 1000000),
  api_token           uuid        not null default gen_random_uuid(),
  first_name          text        not null check (char_length(btrim(first_name)) >= 3),
  last_name           text        not null check (char_length(btrim(last_name)) >= 3),
  country             text        not null check (btrim(country) <> ''),
  state               text        not null check (btrim(state) <> ''),
  city                text,
  email_verified      boolean     not null default false,
  timezone            text        not null default 'America/Mexico_City',
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create table public.email_verification (
  profile_id    uuid        primary key references public.profile (id) on delete cascade,
  code_hash     text        not null,
  expires_at    timestamptz not null,
  attempts      integer     not null default 0,
  last_sent_at  timestamptz not null default now()
);

create table public.xp_event (
  id          bigint      generated by default as identity primary key,
  user_id     uuid        not null references public.profile (id) on delete cascade,
  topic_id    integer,
  exam_id     integer,
  points      integer     not null,
  earned_at   timestamptz not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint xp_event_single_source check ((topic_id is null) <> (exam_id is null)),
  constraint xp_event_points check (
    (topic_id is not null and points = 5) or (exam_id is not null and points = 100)
  )
);

-- Un tema o un examen dan XP una sola vez por usuario (llaves naturales del Outbox)
create unique index xp_event_user_topic_unique on public.xp_event (user_id, topic_id);
create unique index xp_event_user_exam_unique on public.xp_event (user_id, exam_id);

create table public.daily_activity (
  user_id        uuid        not null references public.profile (id) on delete cascade,
  activity_date  date        not null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  primary key (user_id, activity_date)
);

create trigger profile_updated_at before update on public.profile
  for each row execute function public.set_updated_at();
create trigger xp_event_updated_at before update on public.xp_event
  for each row execute function public.set_updated_at();
create trigger daily_activity_updated_at before update on public.daily_activity
  for each row execute function public.set_updated_at();

-- ===================== Seguridad =====================
alter table public.profile enable row level security;
alter table public.email_verification enable row level security;
alter table public.xp_event enable row level security;
alter table public.daily_activity enable row level security;

-- Por si los permisos por defecto ya se habían aplicado antes de esta migración
revoke all on public.profile, public.email_verification, public.xp_event, public.daily_activity
  from anon, authenticated;
revoke execute on function public.set_updated_at() from public, anon, authenticated;

comment on table public.profile is 'Un participante. XP, racha y nivel se calculan; no se guardan aquí.';
