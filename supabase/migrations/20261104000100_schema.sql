comment on column public.profile.api_token is 'Llave que la app manda con el id en cada RPC para demostrar que es el dueño del perfil.';
comment on table public.email_verification is 'Código de verificación vigente (hash, vencimiento, intentos, último envío).';
comment on table public.xp_event is 'Libro de movimientos de XP (append-only). topic_id/exam_id son ids del catálogo local, sin llave foránea.';
comment on table public.daily_activity is 'Días con actividad (día local del usuario), base de la racha.';
